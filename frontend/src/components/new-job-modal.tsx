/**
 * NewJobModal — "The Cutting Table" (Concept 2, wired to the live API).
 *
 * ─────────────────────────────────────────────────────────────────────────
 * DATA FLOW (read this before touching anything)
 * ─────────────────────────────────────────────────────────────────────────
 *
 * The modal mirrors the three folds of the concept: 01 Client, 02 The
 * fitting, 03 The job. Everything a tailor types/taps is accumulated in
 * local state and only hits the API on "Create job". There are two submit
 * paths, and choosing the wrong one corrupts the database, so read this:
 *
 *   1. CLIENT SEARCH
 *      GET /customers is keyset-paginated by name and has NO server-side
 *      search parameter (see customers.validation.ts). A single tailor's
 *      list is small, so we fetch up to the 100-row cap once when the
 *      modal opens and filter in memory. When she outgrows 100 clients,
 *      add a ?q= search to the backend instead of paging here.
 *
 *   2. SUBJECTS ("For whom")
 *      Selecting a returning client calls GET /customers/:id/subjects
 *      (limit 100) and shows Self first, then family subjects. A brand-new
 *      client starts with a single "Self" subject. "+ Add subject" works
 *      for both: new clients keep the subject local (created inside the
 *      /jobs/new-customer transaction), while returning clients persist it
 *      immediately via POST /customers/:id/subjects on ✓ so the job can
 *      link to a real subject id.
 *
 *   3. MEASUREMENTS → jsonb
 *      Selecting a subject that already has a fitting calls
 *      GET /subjects/:id/measurements (newest first) and pre-fills the
 *      chips from the LATEST record. Edits/removals/adds are tracked in
 *      `dirtyMeas` — a touched set becomes a NEW measurements row on
 *      submit so fitting history is never mutated in place.
 *      The chips map to the jsonb the backend expects:
 *      Record<string, number> with camelCase keys ("Sleeve length" →
 *      "sleeveLength"). Keys are auto-generated by `toKey`.
 *
 *   4. SUBMIT — TWO DIFFERENT ENDPOINTS, DO NOT MIX THEM UP
 *      • New client  → POST /jobs/new-customer  (createJob)
 *        One transaction: customer + subject + measurement + job.
 *        subjects[] must contain EXACTLY ONE entry (backend enforces
 *        `.length(1)`), relationship defaults to "self", and the backend
 *        substitutes the customer's name for a self subject.
 *      • Returning client → POST /jobs/:subjectId  (createJobForSubject)
 *        NEVER /jobs/new-customer: that endpoint unconditionally INSERTs
 *        a customer row and would duplicate the client in the database.
 *        createJobForSubject requires an existing measurementId, so if
 *        the tailor touched the measurements (or the subject had none on
 *        file) we first POST /subjects/:id/measurements with today's
 *        date and use the returned id; otherwise we reuse the id of the
 *        latest saved fitting.
 *
 *   5. PHOTOS → signed direct upload, verified server-side
 *      Picking files fetches ONE short-lived signature (GET /jobs/signature,
 *      15-min expiry) and uploads each file straight to Cloudinary
 *      (uploadPhotoToCloudinary — plain fetch, NOT the axios client, whose
 *      interceptor expects the app's ApiResponse envelope). Each tile
 *      tracks its own status (uploading / done / error + retry). On submit
 *      the job carries styleRef as [{ publicId, alt }] — never a URL: the
 *      backend resolves each publicId against Cloudinary and derives the
 *      URL itself. Photos removed BEFORE create are never persisted and
 *      become Cloudinary orphans (a cleanup sweep is the accepted answer at
 *      this scale). The 10 MB cap mirrors the backend's verification limit.
 *
 *   6. DUE DATE
 *      The jobs table stores a `date` column; the UI sends the explicit
 *      "YYYY-MM-DD" string from the native picker and z.coerce.date()
 *      parses it. `status` is omitted so it defaults to "pending".
 * ─────────────────────────────────────────────────────────────────────────
 */
